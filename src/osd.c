static char msg[96];
static uint32_t msg_until;

void osd_message(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(msg, sizeof msg, fmt, ap);
    va_end(ap);
    msg_until = SDL_GetTicks() + 2000;
}

static void draw_text(uint32_t *px, int x, int y, const char *s, uint32_t color);

void osd_clear(uint32_t *ov) { memset(ov, 0, 320 * 240 * 4); }

static void fill(uint32_t *ov, int x0, int y0, int w, int h, uint32_t argb)
{
    for (int y = y0 < 0 ? 0 : y0; y < y0 + h && y < 240; y++)
        for (int x = x0 < 0 ? 0 : x0; x < x0 + w && x < 320; x++) ov[y * 320 + x] = argb;
}

void osd_text(uint32_t *ov, int x, int y, const char *s, uint32_t rgb) { draw_text(ov, x, y, s, rgb); }
void osd_box(uint32_t *ov, int x, int y, int w, int h, uint32_t argb) { fill(ov, x, y, w, h, argb); }

static void draw_text(uint32_t *px, int x, int y, const char *s, uint32_t color)
{
    color |= 0xff000000u;
    for (; *s; s++, x += 6) {
        int c = (unsigned char)*s;
        if (c >= 'a' && c <= 'z') c -= 32;
        if (c < 32 || c > 95) c = '?';
        for (int col = 0; col < 5; col++)
            for (int row = 0; row < 7; row++)
                if (font[c - 32][col] >> row & 1) {
                    int xx = x + col, yy = y + row;
                    if (xx >= 0 && xx < 320 && yy >= 0 && yy < 240) px[yy * 320 + xx] = color;
                }
    }
}

// A dark translucent box with the text in it, so it reads over any background.
static void draw_label(uint32_t *px, int x, int y, const char *s)
{
    fill(px, x, y, (int)strlen(s) * 6 + 5, 11, 0xc0000000u);
    draw_text(px, x + 3, y + 2, s, 0xffffff);
}

void osd_draw(uint32_t *px, const char *status)
{
    if (status && *status) draw_label(px, 320 - 4 - ((int)strlen(status) * 6 + 5), 4, status);
    if (msg[0] && SDL_TICKS_PASSED(SDL_GetTicks(), msg_until)) msg[0] = 0;
    if (msg[0]) draw_label(px, 4, 240 - 15, msg);
}

// A centred panel: title, then one row per item with the selected one highlighted.
// Each item is "label\tvalue" (value optional).
#define MENU_ROWS 18

void osd_menu(uint32_t *px, const char *title, const char *const *items, int n, int sel, const char *footer)
{
    // long pages scroll to keep the selection in view
    static int first;
    int rows = n < MENU_ROWS ? n : MENU_ROWS;
    if (sel < first) first = sel;
    if (sel >= first + rows) first = sel - rows + 1;
    if (first > n - rows) first = n - rows;
    if (first < 0) first = 0;
    int w = 280, row = 10, h = 22 + rows * row + (footer ? 14 : 0);
    int x0 = (320 - w) / 2, y0 = (240 - h) / 2;
    fill(px, 0, 0, 320, 240, 0x90000000u);           // dim the game
    fill(px, x0, y0, w, h, 0xffc08020u);
    fill(px, x0 + 1, y0 + 1, w - 2, h - 2, 0xf0101018u);
    draw_text(px, x0 + (w - (int)strlen(title) * 6) / 2, y0 + 5, title, 0xffc040);
    if (first > 0) draw_text(px, x0 + w - 10, y0 + 5, "^", 0xffc040);
    if (first + rows < n) draw_text(px, x0 + w - 10, y0 + 18 + rows * row - 2, "v", 0xffc040);
    for (int i = first; i < first + rows; i++) {
        int y = y0 + 18 + (i - first) * row;
        char label[64];
        const char *tab = strchr(items[i], '\t');
        size_t len = tab ? (size_t)(tab - items[i]) : strlen(items[i]);
        snprintf(label, sizeof label, "%.*s", (int)len, items[i]);
        if (i == sel) fill(px, x0 + 2, y - 1, w - 4, 9, 0xff604010u);
        uint32_t c = i == sel ? 0xffffff : 0xb0b0b0;
        draw_text(px, x0 + 8, y, label, c);
        if (tab) {
            const char *v = tab + 1;
            draw_text(px, x0 + w - 14 - (int)strlen(v) * 6, y, v, i == sel ? 0xffe080 : 0x80c0ff);
        }
    }
    if (footer) draw_text(px, x0 + (w - (int)strlen(footer) * 6) / 2, y0 + h - 11, footer, 0x808080);
}

const uint8_t *osd_glyph(char c)
{
    int i = (unsigned char)c;
    if (i >= 'a' && i <= 'z') i -= 32;
    if (i < 32 || i > 95) i = '?';
    return font[i - 32];
}
