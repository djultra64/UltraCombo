static char msg[96];
static uint32_t msg_until;

void osd_message(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(msg, sizeof msg, fmt, ap);
    va_end(ap);
    msg_until = SDL_GetTicks() + 2000;
}

static void draw_text(uint32_t *px, int x, int y, const char *s, uint32_t color)
{
    for (; *s; s++, x += 6) {
        int c = (unsigned char)*s;
        if (c >= 'a' && c <= 'z') c -= 32;
        if (c < 32 || c > 95) c = '?';
        for (int col = 0; col < 5; col++)
            for (int row = 0; row < 7; row++)
                if (font[c - 32][col] >> row & 1) {
                    int xx = x + col, yy = y + row;
                    if (xx >= 0 && xx < 320 && yy >= 0 && yy < 240) px[yy * 320 + xx] = color;
                }
    }
}

// A dimmed box with the text in it, so it reads over any background.
static void draw_label(uint32_t *px, int x, int y, const char *s)
{
    int w = (int)strlen(s) * 6 + 5, h = 11;
    for (int yy = y; yy < y + h && yy < 240; yy++)
        for (int xx = x; xx < x + w && xx < 320; xx++)
            if (xx >= 0 && yy >= 0) px[yy * 320 + xx] = (px[yy * 320 + xx] >> 2) & 0x3f3f3f;
    draw_text(px, x + 3, y + 2, s, 0xffffff);
}

void osd_draw(uint32_t *px, const char *status)
{
    if (status && *status) draw_label(px, 320 - 4 - ((int)strlen(status) * 6 + 5), 4, status);
    if (msg[0] && SDL_TICKS_PASSED(SDL_GetTicks(), msg_until)) msg[0] = 0;
    if (msg[0]) draw_label(px, 4, 240 - 15, msg);
}
