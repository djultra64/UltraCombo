#!/usr/bin/env python3
"""Write a C file defining string constants with the contents of files.

usage: embed.py OUT.c name=path [name=path ...]
"""
import sys

with open(sys.argv[1], 'w') as out:
    out.write('// Generated by tools/embed.py. Do not edit.\n')
    for spec in sys.argv[2:]:
        name, path = spec.split('=', 1)
        data = open(path, 'rb').read()
        out.write('const char %s[] =\n' % name)
        for line in data.split(b'\n'):
            text = line.decode('utf-8').replace('\\', '\\\\').replace('"', '\\"')
            out.write('    "%s\\n"\n' % text)
        out.write(';\n')
